const htmlLang = { en: "en", zh: "zh-Hans", fr: "fr-CA" };

function preferred() {
  const saved = localStorage.getItem("holding-cost-lang");
  if (saved && copy[saved]) return saved;
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh")) return "zh";
  if (nav.startsWith("fr")) return "fr";
  return "en";
}

function apply(lang) {
  const table = copy[lang] || copy.en;
  document.documentElement.lang = htmlLang[lang] || "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = table[node.dataset.i18n];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((node) => {
    const value = table[node.dataset.i18nAlt];
    if (value) node.setAttribute("alt", value);
  });
  document.title = document.querySelector("h1")?.textContent
    ? `${document.querySelector("h1").textContent} · ${table.brand}`
    : table.brand;
  document.querySelectorAll(".langs button").forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.lang === lang ? "true" : "false");
  });
  localStorage.setItem("holding-cost-lang", lang);
}

document.querySelectorAll(".langs button").forEach((button) => {
  button.addEventListener("click", () => apply(button.dataset.lang));
});

apply(preferred());
