import Foundation
import Observation

nonisolated enum AppLanguage: String {
    case zhHans = "zh-Hans"
    case en = "en"
    case frCA = "fr-CA"

    var locale: Locale {
        switch self {
        case .zhHans: Locale(identifier: "zh-Hans")
        case .en: Locale(identifier: "en-CA")
        case .frCA: Locale(identifier: "fr-CA")
        }
    }

    static func preferred() -> AppLanguage {
        let available = ["zh-Hans", "en", "fr-CA", "fr"]
        let global = UserDefaults.standard.persistentDomain(forName: UserDefaults.globalDomain)?["AppleLanguages"] as? [String] ?? []
        let chosen = Bundle.preferredLocalizations(from: available, forPreferences: global.isEmpty ? nil : global)
        let locale = Locale.autoupdatingCurrent
        var identifiers = chosen + global + Locale.preferredLanguages + [locale.identifier]
        if let code = locale.language.languageCode?.identifier {
            var composed = code
            if let script = locale.language.script?.identifier { composed += "-\(script)" }
            if let region = locale.region?.identifier { composed += "-\(region)" }
            identifiers.append(composed)
        }
        for identifier in identifiers {
            if let match = matching(identifier) { return match }
        }
        return .en
    }

    private static func matching(_ identifier: String) -> AppLanguage? {
        let locale = Locale(identifier: identifier.replacingOccurrences(of: "_", with: "-"))
        switch locale.language.languageCode?.identifier.lowercased() {
        case "zh": return .zhHans
        case "fr": return .frCA
        case "en": return .en
        default:
            let code = identifier.replacingOccurrences(of: "_", with: "-").lowercased()
            if code.hasPrefix("zh") { return .zhHans }
            if code.hasPrefix("fr") { return .frCA }
            if code.hasPrefix("en") { return .en }
            return nil
        }
    }
}

@Observable
final class LanguageSettings {
    var language: AppLanguage {
        didSet { L10n.language = language }
    }

    init() {
        UserDefaults.standard.removeObject(forKey: "app.language")
        let language = ScreenshotLaunch.mode == nil ? AppLanguage.preferred() : .en
        self.language = language
        L10n.language = language
    }

    func applySystemLocale() {
        if ScreenshotLaunch.mode != nil { return }
        let next = AppLanguage.preferred()
        if language != next {
            language = next
        } else {
            L10n.language = next
        }
    }

    func t(_ key: String, _ args: CVarArg...) -> String {
        L10n.format(language, key, args)
    }
}

nonisolated enum L10n {
    nonisolated(unsafe) static var language: AppLanguage = AppLanguage.preferred()

    static func t(_ key: String, _ args: CVarArg...) -> String {
        format(language, key, args)
    }

    static func isDefaultName(_ name: String) -> Bool {
        let trimmed = name.trimmingCharacters(in: .whitespacesAndNewlines)
        if trimmed.isEmpty || trimmed == "新建公寓" || trimmed == "未命名公寓" { return true }
        return [zh, en, fr].contains {
            $0["property.new"] == trimmed || $0["house.new.detached"] == trimmed || $0["house.new.townhouse"] == trimmed
        }
    }

    static func format(_ language: AppLanguage, _ key: String, _ args: [CVarArg]) -> String {
        let template = catalog(language)[key] ?? catalog(.en)[key] ?? catalog(.zhHans)[key] ?? key
        guard !args.isEmpty else { return template }
        return String(format: template, locale: language.locale, arguments: args)
    }

    private static func catalog(_ language: AppLanguage) -> [String: String] {
        switch language {
        case .zhHans: zh
        case .en: en
        case .frCA: fr
        }
    }
}

